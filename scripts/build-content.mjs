// Bakes blog posts (app/posts/*.mdx) and snippets (snippets/*.md) into app/content.generated.ts,
// so the server build carries them instead of reading files at runtime. Vercel's Remix builder
// doesn't ship files read from disk, so runtime reads 404 there. Runs before build and dev.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (dir, ext) =>
  Object.fromEntries(
    fs
      .readdirSync(path.join(root, dir))
      .filter((f) => f.endsWith(ext))
      .sort()
      .map((f) => [f, fs.readFileSync(path.join(root, dir, f), "utf8")]),
  );

const posts = read("app/posts", ".mdx");
const snippets = read("snippets", ".md");
const out = `// AUTO-GENERATED by scripts/build-content.mjs. Do not edit: change app/posts or snippets instead.
/* eslint-disable */
export const POST_FILES: Record<string, string> = ${JSON.stringify(posts, null, 2)};

export const SNIPPET_FILES: Record<string, string> = ${JSON.stringify(snippets, null, 2)};
`;
const target = path.join(root, "app", "content.generated.ts");
if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== out) fs.writeFileSync(target, out);
console.log(`content: ${Object.keys(posts).length} posts, ${Object.keys(snippets).length} snippets`);
